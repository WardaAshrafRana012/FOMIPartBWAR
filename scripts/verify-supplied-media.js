import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const b=await chromium.launch({channel:'chrome'}),p=await b.newPage({viewport:{width:1440,height:900}}),errors=[];
p.on('pageerror',e=>errors.push(e.message));
await p.goto(process.env.BASE_URL||'http://localhost:3108');await p.locator('#prompt').waitFor();
const v=p.locator('.stage video');await v.evaluate(v=>v.play());await p.waitForTimeout(350);
assert.ok((await v.getAttribute('src')).includes('study-reveal'));assert.ok(await v.evaluate(v=>v.currentTime)>0);
assert.equal(await p.locator('.take-card').count(),2);
await p.getByRole('button',{name:'Watch full sample films',exact:false}).click();
await p.getByRole('heading',{name:'Full sample films'}).waitFor();
const sample=p.locator('dialog video').first();await sample.evaluate(v=>v.play());await p.waitForTimeout(350);
assert.ok(await sample.evaluate(v=>v.duration)>17);assert.equal(await sample.evaluate(v=>v.videoWidth),720);
await p.keyboard.press('Escape');assert.equal(await sample.count(),0);
await p.getByRole('button',{name:'Compare takes',exact:true}).click();
const options=await p.getByLabel('Comparison 1').locator('option').allTextContents();
assert.ok(!options.some(s=>s.includes('Sample')));await p.keyboard.press('Escape');
await p.getByRole('button',{name:'Review sequence',exact:false}).click();const review=p.locator('dialog video');
await review.evaluate(v=>v.play());await p.waitForTimeout(250);
await review.evaluate(async v=>{v.currentTime=v.duration-.4;await new Promise(r=>v.addEventListener('seeked',r,{once:true}));await v.play();});
await p.waitForFunction(()=>document.querySelector('dialog video')?.getAttribute('src').includes('study-texture'));
await p.keyboard.press('Escape');await p.setViewportSize({width:390,height:844});
assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);await b.close();console.log('PASS chosen short clip, separate full-film library, shot-only comparison, sequence advance and mobile');
