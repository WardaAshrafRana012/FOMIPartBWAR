import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const b=await chromium.launch({channel:'chrome'}),p=await b.newPage({viewport:{width:1440,height:900}});
const errors=[];p.on('pageerror',e=>errors.push(e.message));
await p.goto(process.env.BASE_URL||'http://localhost:3104');await p.locator('#prompt').waitFor();
const v=p.locator('.stage video');await v.evaluate(el=>el.play());await p.waitForTimeout(600);
assert.ok(await v.evaluate(el=>el.currentTime)>0);assert.ok(await v.evaluate(el=>el.duration)>17);
assert.equal(await v.evaluate(el=>el.videoWidth),720);
await v.evaluate(el=>el.pause());await p.screenshot({path:'docs/screenshots/supplied-desktop.png'});
await p.getByRole('button',{name:'Choose this take',exact:true}).click();
await p.waitForTimeout(650);await p.reload();await p.locator('#prompt').waitFor();
assert.ok((await p.locator('.stage video').getAttribute('src')).endsWith('supplied-01.mp4'));
await p.getByRole('button',{name:'Take details',exact:false}).click();
await p.getByText('Supplied sample footage ·', {exact:false}).waitFor();
await p.keyboard.press('Escape');
await p.getByRole('button',{name:'Review sequence',exact:false}).click();
const review=p.locator('dialog video');await review.evaluate(el=>el.play());await p.waitForTimeout(200);
await review.evaluate(async el=>{el.currentTime=el.duration-.4;await new Promise(r=>el.addEventListener('seeked',r,{once:true}));await el.play();});
await p.waitForFunction(()=>!document.querySelector('dialog video')?.getAttribute('src').includes('supplied-01'),{},{timeout:10000});
assert.ok(!(await review.getAttribute('src')).includes('supplied-01'));
await p.keyboard.press('Escape');await p.setViewportSize({width:390,height:844});
await p.screenshot({path:'docs/screenshots/supplied-mobile.png'});
assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);await b.close();console.log('PASS actual supplied MP4 decode, playback, metadata, persistent choice, sequence advance and mobile');
