import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel:'chrome'});
const page = await browser.newPage({viewport:{width:1440,height:900}});
await page.goto(process.env.BASE_URL || 'http://localhost:3102');
await page.locator('#prompt').waitFor();
await page.getByRole('button',{name:'Storyboard',exact:true}).click();
await assert.equal(await page.getByRole('button',{name:'Storyboard',exact:true}).getAttribute('aria-pressed'),'true');
await assert.equal(await page.locator('.direction-panel').isVisible(),false);
await page.locator('.storyboard .shot-select').nth(1).click();
await page.getByRole('button',{name:'Director',exact:true}).click();
await assert.equal(await page.locator('.direction-panel').isVisible(),true);
await page.locator('.atelier-views').getByRole('button',{name:'Sequence',exact:true}).click();
await page.getByRole('dialog').waitFor();
await page.keyboard.press('Escape');
await page.locator('.shot-select').first().hover();
await page.waitForTimeout(450);
assert.notEqual(await page.locator('.shot-thumb img').first().evaluate(el=>getComputedStyle(el).transform),'none');
await page.emulateMedia({reducedMotion:'reduce'});
assert.equal(await page.locator('.shot-thumb img').first().evaluate(el=>getComputedStyle(el).transitionDuration),'0s');
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'docs/screenshots/unified-mobile.png'});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await browser.close();
console.log('PASS storyboard/director/sequence switching, hover, reduced motion and mobile overflow');
